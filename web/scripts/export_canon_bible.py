def export_pdf(docx_path: Path) -> Path:
    """Convert via Microsoft Word COM (best Cyrillic fidelity on Windows)."""
    try:
        import win32com.client  # type: ignore
    except ImportError:
        print("pywin32 missing; trying pip install")
        import subprocess
        import sys

        subprocess.check_call([sys.executable, "-m", "pip", "install", "pywin32", "-q"])
        import win32com.client  # type: ignore

    word = win32com.client.Dispatch("Word.Application")
    word.Visible = False
    try:
        doc = word.Documents.Open(str(docx_path.resolve()))
        # 17 = wdFormatPDF
        out = PDF if docx_path.resolve() == DOCX.resolve() else docx_path.with_suffix(".pdf")
        if out.exists():
            try:
                out.unlink()
            except OSError:
                out = out.with_name(out.stem + "-updated.pdf")
        doc.SaveAs(str(out.resolve()), FileFormat=17)
        doc.Close(False)
        print("wrote", out)
        return out
    finally:
        word.Quit()


